const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
const file = fs.readFileSync('src/app/(auth)/sign-in.tsx', 'utf8');
const logoSource = fs.readFileSync('assets/waits-clock-logo.ts', 'utf8');
const logoModule = { exports: {} };
const compiled = ts.transpileModule(logoSource, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
require('node:vm').runInNewContext(compiled, { exports: logoModule.exports });
const xml = logoModule.exports.WAITS_CLOCK_LOGO_XML;
assert.match(file, /screen:\s*\{\s*flex:\s*1,\s*backgroundColor:\s*'#000000'/);
assert.match(file, /brand:\s*\{\s*alignItems:\s*'center'\s*\}/);
assert.equal((file.match(/<SvgXml\s+xml=\{WAITS_CLOCK_LOGO_XML\}/g) ?? []).length, 1);
assert.doesNotMatch(file, /<Image\b|backgroundColor:\s*colors\.blue|backgroundColor:\s*'#(?:0088FF|0088ff|0A84FF)'/);
assert.doesNotMatch(xml, /<rect\b|<image\b|fill=["'](?:black|#000(?:000)?)["']/i);
assert.match(file, /AppleAuthenticationButtonType\.SIGN_IN/);
assert.match(file, /Sign in with Google/);
assert.match(file, /Continue with Email/);
assert.match(file, /const GOOGLE_REDIRECT = 'waits:\/\/sign-in'/);
assert.doesNotMatch(file, /phone-pad|Phone Number|Sign in with Phone/i);
assert.match(fs.readFileSync('src/app/onboarding.tsx', 'utf8'), /router\.replace\('\/\(auth\)\/sign-in'\)/);
console.log('Native onboarding sign-in source checks passed: black screen, one unboxed transparent approved logo, unchanged Apple/Google/email options and callback. Physical iPhone rendering not tested.');
